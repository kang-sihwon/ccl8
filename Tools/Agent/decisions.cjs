#!/usr/bin/env node
'use strict';

// Generates Docs/Decisions.md from the frontmatter of Docs/decisions/NNNN-*.md and checks decision links.
// Usage: node Tools/Agent/decisions.cjs check | generate [--write] | next

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { parseFrontmatter } = require('./skills.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const DECISIONS_DIR = 'Docs/decisions';
const INDEX_FILE = 'Docs/Decisions.md';
const FILE_NAME = /^(\d{4})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/;
const STATUSES = new Set(['유효', '유효(부분)', '번복', '완료', '미확인']);
const REQUIRED = ['number', 'date', 'title', 'topic', 'status', 'summary', 'owners'];
// Relation key, wording on the newer decision, wording on the older decision it points at.
const RELATIONS = [
  ['refines', '구체화', '에서 구체화'],
  ['amends', '보완', '에서 보완'],
  ['supersedes_part', '일부 대체', '에서 일부 대체'],
  ['supersedes', '대체', '에서 대체'],
  ['lifts_hold', '보류 해제', '에서 보류 해제'],
];
const DECISION_LINK = /\[([^\]]*결정 \d+[^\]]*)\]\(([^)\s]+)\)/g;
const ANY_LINK = /\]\(([^)\s#]+)(?:#[^)]*)?\)/g;

const numberList = value => (value ? value.replace(/^\[|\]$/g, '').split(',').map(item => item.trim()).filter(Boolean).map(Number) : []);

function loadDecisions(root) {
  const dir = path.join(root, DECISIONS_DIR);
  const findings = [];
  const decisions = [];
  for (const name of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
    if (!name.endsWith('.md')) continue;
    const file = `${DECISIONS_DIR}/${name}`;
    const match = name.match(FILE_NAME);
    if (!match) {
      findings.push(`${file}: file name is not NNNN-english-kebab.md`);
      continue;
    }
    const text = fs.readFileSync(path.join(dir, name), 'utf8');
    const fields = parseFrontmatter(text);
    if (!fields) {
      findings.push(`${file}: frontmatter block is missing`);
      continue;
    }
    for (const key of REQUIRED) {
      if (!fields[key]) findings.push(`${file}: frontmatter "${key}" is missing`);
    }
    const number = Number(fields.number);
    if (number !== Number(match[1])) findings.push(`${file}: number ${fields.number} does not match the file name`);
    if (fields.status && !STATUSES.has(fields.status)) findings.push(`${file}: status "${fields.status}" is not one of ${[...STATUSES].join(', ')}`);
    const heading = `# ${fields.date} — 결정 ${number}: ${fields.title}`;
    if (!text.split(/\r?\n/).includes(heading)) findings.push(`${file}: heading "${heading}" is missing`);
    const relations = Object.fromEntries(RELATIONS.map(([key]) => [key, numberList(fields[key])]));
    decisions.push({ ...fields, number, file: name, relations });
  }
  const numbers = new Set(decisions.map(decision => decision.number));
  decisions.forEach((decision, index) => {
    if (decision.number !== index + 1) findings.push(`${DECISIONS_DIR}/${decision.file}: expected decision ${index + 1} at this position`);
    for (const [key, targets] of Object.entries(decision.relations)) {
      for (const target of targets) {
        if (!numbers.has(target) || target >= decision.number) findings.push(`${DECISIONS_DIR}/${decision.file}: ${key} names decision ${target}, which is not an earlier decision`);
      }
    }
  });
  return { decisions, findings };
}

function relationText(decision, decisions) {
  const parts = [];
  for (const [key, forward] of RELATIONS) {
    for (const target of decision.relations[key]) parts.push(`결정 ${target} ${forward}`);
  }
  for (const [key, , backward] of RELATIONS) {
    for (const other of decisions) {
      if (other.relations[key].includes(decision.number)) parts.push(`결정 ${other.number}${backward}`);
    }
  }
  return parts.join(', ');
}

function render(decisions) {
  const cell = text => text.replace(/\|/g, '\\|');
  const rows = decisions.map(decision => {
    const status = decision.progress ? `${decision.status}, ${decision.progress}` : decision.status;
    const owners = decision.owners.replace(/\]\(\.\.\//g, '](');
    return `| [결정 ${decision.number}](decisions/${decision.file}) | ${cell(decision.topic)} | ${cell(decision.summary)} | ${cell(status)} | ${relationText(decision, decisions)} | ${owners} |`;
  });
  return [
    '# 현재 설계 결정',
    '',
    '<!-- Generated by `node Tools/Agent/decisions.cjs generate --write` from Docs/decisions/. Edit the decision files, not this table. -->',
    '',
    '결정 하나의 배경, 결정, 트레이드오프는 `Docs/decisions/`의 파일이 소유한다. 이 표는 각 파일의 머리말에서 만든다. 결정의 추가·번복 절차는 [결정 기록](WritingGuide/DecisionRecords.md#결정을-기록하는-방법)를 따른다. 초기 개발 환경의 확정 사항은 [Setup](Setup.md)에 있다.',
    '',
    '| 결정 | 주제 | 현재 내용 | 상태 | 관계 | 소유 문서 |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
    '위 결정으로 확정한 범위 밖의 [GameDesign](GameDesign.md), [ArtDirection](ArtDirection.md) 세부 제안과 [StudyRoadmap](StudyRoadmap.md)의 월별 배분은 후보로 유지한다.',
    '',
  ].join('\n');
}

function trackedMarkdown(root) {
  const output = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '*.md'], { cwd: root, encoding: 'utf8' });
  return output.split(/\r?\n/).filter(file => file && !file.startsWith('graft/'));
}

function checkLinks(root, decisions) {
  const findings = [];
  const byFile = new Map(decisions.map(decision => [decision.file, decision.number]));
  const designLog = path.join(root, 'Docs', 'DesignLog.md');
  for (const file of trackedMarkdown(root)) {
    const full = path.join(root, file);
    if (!fs.existsSync(full)) continue;
    const lines = fs.readFileSync(full, 'utf8').split(/\r?\n/);
    lines.forEach((line, index) => {
      const where = `${file}:${index + 1}`;
      for (const [, target] of line.matchAll(ANY_LINK)) {
        if (/^[a-z]+:/i.test(target)) continue;
        if (path.resolve(path.dirname(full), decodeURIComponent(target)) === designLog) findings.push(`${where}: links to the retired Docs/DesignLog.md`);
      }
      for (const [, text, target] of line.matchAll(DECISION_LINK)) {
        const numbers = [...text.matchAll(/결정 (\d+)/g)].map(match => Number(match[1]));
        const resolved = path.resolve(path.dirname(full), decodeURIComponent(target.split('#')[0]));
        if (path.dirname(resolved) !== path.join(root, ...DECISIONS_DIR.split('/'))) continue;
        const number = byFile.get(path.basename(resolved));
        if (number === undefined) findings.push(`${where}: "${text}" links to a missing decision file ${target}`);
        else if (numbers.length !== 1 || numbers[0] !== number) findings.push(`${where}: "${text}" links to decision ${number}`);
      }
    });
  }
  return findings;
}

function main(argv, root) {
  const [mode, ...flags] = argv;
  const { decisions, findings } = loadDecisions(root);
  const indexPath = path.join(root, INDEX_FILE);
  const expected = render(decisions);
  if (mode === 'next') {
    const next = decisions.length + 1;
    process.stdout.write(`${DECISIONS_DIR}/${String(next).padStart(4, '0')}-<english-kebab-slug>.md (결정 ${next})\n`);
    return 0;
  }
  if (mode === 'generate') {
    if (findings.length) {
      for (const finding of findings) process.stdout.write(`ERROR ${finding}\n`);
      return 1;
    }
    if (flags.includes('--write')) fs.writeFileSync(indexPath, expected);
    else process.stdout.write(expected);
    return 0;
  }
  if (mode === 'check') {
    const actual = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, 'utf8').replace(/\r\n/g, '\n') : '';
    if (actual !== expected) findings.push(`${INDEX_FILE} differs from the generated table; run generate --write`);
    findings.push(...checkLinks(root, decisions));
    for (const finding of findings) process.stdout.write(`ERROR ${finding}\n`);
    process.stdout.write(`${decisions.length} decision(s), ${findings.length} error(s)\n`);
    return findings.length ? 1 : 0;
  }
  process.stderr.write('Usage: node Tools/Agent/decisions.cjs check | generate [--write] | next\n');
  return 2;
}

if (require.main === module) {
  process.exitCode = main(process.argv.slice(2), ROOT);
}

module.exports = { loadDecisions, render, checkLinks, main };
